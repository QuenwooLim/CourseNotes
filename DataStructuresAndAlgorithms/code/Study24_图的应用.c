/*
图的生成树：所有顶点均由边链接在一起，但不存在回路的图
一个图可以有很多个不同生成树
生成树的顶点个数和图的顶点个数相同
生成树是图的极小连通子图（去掉一条边则不连通）
一个有n个顶点的连通图的生成树有n-1条边，不多不少
任意两点之间的路径是唯一的
*/

