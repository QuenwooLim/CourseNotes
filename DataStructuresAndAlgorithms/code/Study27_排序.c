/*
排序：将一组杂乱无章的数据按一定规律排列起来
      即将无序序列排成有序序列（从小到大或从大到小）

排序方法的分类
按数据存储介质：内部排序和外部排序
  内部排序：数据在内存，数据量不大
  外部排序：数据在外存，数据量较大  
           （需要将数据分批调入内存排序，中间结果及时放入外存，更复杂
按比较器个数：串行排序和并行排序
  串行排序：单处理机，同一时刻比较一对元素
  并行排序：多处理机，同一时刻比较多对元素
按主要操作：比较排序和技术排序
  比较排序：插入排序，交换排序，选择排序，归并排序
  技术排序：不需要比较，按照元素的值就能知道其在序列位置
按辅助空间：原地排序和非原地排序
  原地排序：辅助空间用量为O(1)
  非原地排序：辅助空间用量超过O(1)
按稳定性：稳定排序和非稳定排序，支队结构类型数据排序有意义
  稳定排序：能够使任何数值相等的元素，排序以后相对次序不变
  不稳定排序：反之
按自然性：自然排序和非自然排序
  自然排序：输入数据越有序，排序的速度越快
  非自然排序：反之
*/

#define MAXSIZE 20  //设置记录最大为20、
#define KeyType int //设置关键字为int类型
typedef struct//定义记录(表中的数据元素)的结构
{
    KeyType key;//关键字
    //... 其他数据域
}RedType;//Record Type
typedef struct//定义顺序表的结构
{
    RedType r[MAXSIZE + 1];//数组   +1：r[0]作为哨兵或者缓冲区
    int length;//记录表长
}SqList;
//此处所有的排序知识都是基于这里的顺序表结构

/*
插入排序
i位置下标的元素要插入时
0到i-1下标的元素是有序的，i到MAXSIZE元素是无序的

顺序性法：定位插入位置->直接插入排序
二分法：定位插入位置->二分插入排序
缩小增量：多遍插入排序->希尔排序
*/

/*
顺序性法：定位插入位置->直接插入排序
  1.顺序查找:
    用x保留i下标的元素值，下标j从i-1到0的值依次于x进行比较
    若r[j]>x，则r[j+1]=r[j]
    若r[j]<x，则r[j+1]=x
  2.使用“哨兵”:
    先判断i是否比前一个元素小，若是则开启哨兵模式，将r[0]=r[i]
    比较大小进行定位
*/
void InsertSort(SqList* L)
{
    int i = 0;
    int j = 0;
    for (i = 2; i <= L->length; ++i)//从2开始将每一个元素都循环排序一遍
    {
        if (L->r[i].key < L->r[i - 1].key)
            L->r[0] = L->r[i];//哨兵
        for (j = i - 1;L->r[j].key>L->r[0].key; j--)
        {
            L->r[j + 1] = L->r[j];//后移
        }
        L->r[j + 1] = L->r[0];
    }
}
/*
时间复杂度
最好情况(只比较,不用移动) O(n)
最坏情况(输入数据逆有序) O(n^2)
平均情况耗时差不多是最坏情况的一半 O(n^2)
*/


/*
二分法：定位插入位置->二分插入排序
序列的前半部分是有序的，直接利用折半查找定位
  1.利用二分法定位 当low>high跳出循环 high+1为插入位置
  2.将high以后的元素依次向后移动一个
  3.再插入元素
*/
void BInsertSort(SqList* L)
{
    int i = 0;
    int j = 0;
    for (i = 2; i < MAXSIZE; i++)
    {
        L->r[0] = L->r[i];//哨兵
        int low = 1;
        int high = i - 1;
        while (low <= high)
        {
            int mid = (low + high) / 2;
            if (L->r[0].key < L->r[mid].key)
                high = mid - 1;
            else
                low = mid + 1;
        }//跳出循环时 high+1为循环插入位置
        for (j = i - 1; j >= high + 1; --j)
            L->r[j + 1] = L->r[j];//high以后的元素依次后移
        L->r[high] = L->r[0];
    }
}
/*
减少了比较次数，但没有减少移动次数
平均性能优于直接插入排序 特别当n足够大时
时间复杂度 O(n^2)
空间内复杂度O(1)
是一种稳定的排序方法
*/

/*
希尔排序：逐渐缩小增量，多遍插入排序
先将整个待排记录序列分割成若干个子序列，分别进行直接插入排序，
待整个序列中的记录基本有序时，再对全体记录进行依次直接插入排序
即先大量跳跃移动，最后直接插入排序少量移动

1.定义增量序列D,D是递减且互质的
2.对每个增量d进行跳跃式的插入排序
eg:第一次d取5，则每隔5个元素对子序列进行排序
   第二次d取3，则每隔3个元素对子序列进行排序
   第三次d取1，则每隔1个元素对子序列进行排序 (最后一次d=1即直接插入排序
*/

void ShellInsert(SqList* L, int d)//增量为d的插入排序
{
    int i = 0;
    int j;
    for (i = d + 1; i <= L->length; i++)
    {
        if (L->r[i].key < L->r[i - d].key)
        {
            L->r[0] = L->r[i];//r[0]是暂存单元防止被覆盖，不是哨兵
            for (j = i - d; j > 0 && (L->r[0].key < L->r[j].key); j = j - d)
                L->r[j + d] = L->r[j];
            L->r[j + d] = L->r[0];
        }
    }
}//分组交叉着排序
void ShellSort(SqList* L, int dlta[], int t)//希尔排序的主程序
//每一个增量d依次存在dlta[t]中 按照增量排序dlta[0...t-1]对顺序表L作希尔排序
{
    int k = 0;
    for (k = 0; k < t; ++k)
    {
        ShellInsert(L, dlta[k]);//增量为dlta[k]的插入排序
    }
}
