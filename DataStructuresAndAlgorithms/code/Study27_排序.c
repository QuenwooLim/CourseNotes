/*
冒泡排序：每趟不断将前后两个元素比较 交换位置
          第一趟比较最大值在最后面 第二趟比较倒数第二大...
          n个记录 需要比较n-1趟 第m趟比较需要比较n-m次
          做一个标记flag 若某一趟没没交换 则提前结束排序
*/
void bubble_sort(SqList* L)
{
    int n = MAXSIZE;
    int m, i, j, flag = 1;
    RedType x;//暂存结点
    for (m = 1; (m <= n - 1)&&(flag==1); m++)
    {
        flag = 0;//没发生交换的标志
        for (j = 1; j <= n - m; j++)
        {
            if (L->r[j].key < L->r[j + 1].key)//发生交换
            {
                flag = 1;//发生交换过的标志
                x = L->r[j];
                L->r[j] = L->r[j + 1];
                L->r[j + 1] = x;
            }
        }
    }
}
/*
时间复杂度
最好情况：比较n-1
          移动0
最坏情况：比较(n-1)*n/2
          移动3*(n-1)*n/2

平均时间复杂度O(n^2)
辅助空间S(n)=O(1)
冒泡排序是稳定的
*/

/*
快速排序
选一个记录作为中间数，所有元素与它相比，小的在左边，大的在右边
再对中间数左边，右边的子序列进行递归操作，直到子序列中只有一个元素

pivotloc中间数(枢轴)：可以是第一个数，最后一个数，最中间一个数，任选一个

为节省空间，可在表的两头设置low high 向中间交替必进
*/
void main()
{
    SqList L;
    QSort(&L, 1, L.length);
}
int Partition(SqList* L, int low, int high)//快速排序子程序
{
    int pivotkey = L->r[low].key;//选取r[row]即r[1]的值作为中间数
    L->r[0] = L->r[low];//先将选取的中间数(即low下标的数)存放在r[0]
    while (low < high)
    {
        while (low < high && L->r[high].key >= pivotkey)
            --high;//high一直向前推直到找到了小于中间数的记录
        L->r[low] = L->r[high];//low的位置已经空出来了
        while (low < high && L->r[low].key <= pivotkey)
            ++low;//low一直向后推直到找到了小于中间数的记录
        L->r[high] = L->r[low];//high的位置已经空出来了
    }//循环结束时low==high
    L->r[low] = L->r[0];
    return low;//放回中间数排序后的位置

}
void QSort(SqList* L, int low, int high)//快速排序主程序
{
    if (low < high)
    {
        int pivotloc = Partition(L, low, high);//排序并且 函数返回找中间数
        QSort(L, low, pivotloc - 1);//低子表递归
        QSort(L, pivotloc + 1 ,high);//高子表递归
    }
}

/*
快速排序算法分析

空间复杂度：
平均计算时间O(n*lgn/lg2)
  Qsort:O(lgn/lg2)
  Partition:O(n)
实验证明 快速排序时所有内排序方法中最好效率最高的一个

时间复杂度：
快速排序不是原地排序，使用了递归，需要调用栈
平均栈空间O(lgn)
最坏情况栈空间O(n)

快速排序是一种不稳定排序方法
快速排序不是自然排序方法，不适合对原本有序或基本有序的记录序列进行排序
  eg 90 85 76 74 68 50 46  则退化成冒泡排序
*/


/*
简单选择排序
在待排序的序列中选出最大(或小)的元素放在其最终的位置
通过n-1次比较，在n个记录找出最小值，和第一个记录交换
通过n-2次比较，在除第一个的n-1个记录中找出最小值，和第二个记录交换
...
共执行n-1趟 完成排序（每一趟排好一个记录）
*/
void SelectSort(SqList* L)
{
    int i = 0;
    int j = 0;
    for (i = 1; i < L->length; i++)
    {
        int k = i;
        for (j = i + 1; j <= L->length; j++)
        {
            if (L->r[j].key < L->r[k].key)//记录最小值
                k = j;
        }
        L->r[i] = L->r[k];
    }
}
